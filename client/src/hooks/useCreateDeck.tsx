import { request } from "../utils/fetch-utils";
import { useMutation, useQueryClient } from "@tanstack/react-query";
import { AlertContext } from "../context/AlertContext";
import { DeckAndCardType, DeckType } from "../types/types";
import { useContext } from "react";

const createDeck = async (title: string) => {
  try {
    // you don't need to add try catch block as axios will automatically throw an error.
    // If you want to throw an error then do it manually  using throw keyword because usequery or usemutation need that
    const data = await request.post(`/deck`, { title });
    if (data?.message) {
      return { message: data?.message, status: data?.status };
    } else {
      return data?.data;
    }
  } catch (error) {
    return {
      message:
        "An unexpected error occurred while creating the deck. Please try again later.",
      status: 400,
    };
  }
};

const useCreateDeck = () => {
  const { setAlert } = useContext(AlertContext);
  const queryClient = useQueryClient();
  // whatever we pass to useMutations mutate function that will be reaceived in the createDeck function and in onMutate and other properities of useMutation.
  return useMutation({
    mutationFn: createDeck,
    onMutate: async (title: string) => {
      await queryClient.cancelQueries({ queryKey: ["decks"] });
      // onMutate runs before sending the request to the server. Here we assume that everything is going to be fine.
      // Cancel any outgoing refetches (so they don't overwrite our optimistic update)
      const previousQueryData: DeckType[] = queryClient.getQueryData([
        "decks",
      ])!;
      queryClient.setQueryData(
        ["decks"],
        (oldQueryData: DeckType[] | undefined) => {
          if (oldQueryData) {
            return [
              {
                title,
                _id: Math.random().toString(),
                pinned: false,
                isProcessing: true,
              },
              ...oldQueryData,
            ];
          } else {
            return [];
          }
        }
      );

      await queryClient.cancelQueries({ queryKey: ["decks-and-cards"] });

      const previousQueryDataForSearch: DeckAndCardType[] =
        queryClient.getQueryData(["decks-and-cards"])!;
      if (previousQueryDataForSearch) {
        queryClient.setQueryData(
          ["decks-and-cards"],
          (oldQueryData: DeckAndCardType[] | undefined) => {
            if (oldQueryData) {
              return [
                {
                  title,
                  _id: Math.random().toString(),
                  pinned: false,
                  cards: [],
                },
                ...oldQueryData,
              ];
            } else {
              return [];
            }
          }
        );
      }

      // Return previous data so that if something goes wrong we can use this in onError method
      return { previousQueryData, previousQueryDataForSearch };
    },

    onSuccess: (data, _variables, _context) => {
      // While doing optimistic updates, we add a dummy _id. Once the request returns a successful response, we replace the dummy _id with the original _id generated by the database. If we don't do this and the user creates a deck and immediately clicks on it, the app will try to access the deck with the dummy _id, which does not exist in the database.
      if (!data?.message) {
        const { _id } = data;
        const allDecks: DeckType[] | undefined = queryClient.getQueryData([
          "decks",
        ]);
        queryClient.setQueryData(
          ["decks"],
          (oldQueryData: DeckType[] | undefined) => {
            if (oldQueryData) {
              return oldQueryData.map((deck) =>
                deck._id === allDecks![0]._id
                  ? { ...deck, _id, isProcessing: false } // Replace temporary id with actual id
                  : deck
              );
            } else {
              return [];
            }
          }
        );

        const allDecksAndCards: DeckAndCardType[] | undefined =
          queryClient.getQueryData(["decks-and-cards"]);
        queryClient.setQueryData(
          ["decks-and-cards"],
          (oldQueryData: DeckAndCardType[] | undefined) => {
            if (oldQueryData) {
              return oldQueryData.map((deck) =>
                deck._id === allDecksAndCards![0]._id
                  ? { ...deck, _id } // Replace temporary id with actual id
                  : deck
              );
            } else {
              return [];
            }
          }
        );
      } else {
        if (data && "message" in data) {
          if (data?.message) {
            throw new Error(data?.message);
          } else {
            throw new Error(
              "An unexpected error occurred while creating the deck. Please try again later!"
            );
          }
        }
      }
    },

    onError: (error, _title, context) => {
      // I have returned the previous query data in onMutate function I can receive that data in context. I can use that data to
      // reverse what I have done in onMutate because onMutate runs before request goes to server there I have assumed that
      // Everthing will be fine on the server and I did optimistic updates in onMutate function. If some error occures I will
      // reverse that here using previousQuery dataW
      queryClient.setQueryData(["decks"], context?.previousQueryData);
      queryClient.setQueryData(
        ["decks-and-cards"],
        context?.previousQueryDataForSearch
      );
    },

    // onSettled is called in the end it doesnt matter if the mutation is successful or failed it will be called everytime. After doing above operations we will refetch the data. so that our data and the data in the db will be in sync.
    onSettled: () => {
      queryClient.invalidateQueries({ queryKey: ["decks"] });
    },
  });
};

export default useCreateDeck;
